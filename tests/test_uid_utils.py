class TestValidateUid:
    """Coverage: valid format, wrong length, non-hex chars, empty string."""

    def test_accepts_valid_64_char_hex(self) -> None:
        """A real UID generated by generate_uid must be valid."""
        uid = generate_uid("qidian:123", "诡秘之主")
        assert validate_uid(uid) is True

    def test_accepts_manual_valid_hex(self) -> None:
        """64 lowercase hex digits are accepted."""
        uid = "a" * 64
        assert validate_uid(uid) is True

    def test_accepts_mixed_digits(self) -> None:
        """All hex characters (0-9, a-f) work."""
        uid = "0123456789abcdef" * 4  # exactly 64 chars
        assert len(uid) == 64
        assert validate_uid(uid) is True

    def test_rejects_too_short(self) -> None:
        """Fewer than 64 characters is invalid."""
        assert validate_uid("a" * 63) is False

    def test_rejects_too_long(self) -> None:
        """More than 64 characters is invalid."""
        assert validate_uid("a" * 65) is False

    def test_rejects_non_hex_chars(self) -> None:
        """Characters outside 0-9, a-f (and A-F) are invalid."""
        # 'g' is not valid hex
        assert validate_uid("g" + "a" * 63) is False
        # 'z' is not valid hex
        assert validate_uid("a" * 63 + "z") is False
        # uppercase G
        assert validate_uid("a" * 63 + "G") is False

    def test_rejects_empty_string(self) -> None:
        """Empty string has length 0, not 64."""
        assert validate_uid("") is False

    def test_accepts_uppercase_hex(self) -> None:
        """int(..., 16) accepts uppercase, so validate_uid accepts it too."""
        assert validate_uid("A" * 64) is True

    def test_rejects_none(self) -> None:
        """None is not a string; validate_uid raises."""
        import pytest

        with pytest.raises((AttributeError, TypeError)):
            validate_uid(None)  # type: ignore[arg-type]
